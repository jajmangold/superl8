// IQ2_XS decode -- warp-per-column MMVQ over ggml's 512-entry grid.
// Block (74 B / 256 weights, 2.3125 bpw):
//     +0   d          fp16 super-block scale
//     +2   qs[32]     uint16: low 9 bits = grid index, top 7 bits = ksigns index
//     +66  scales[8]  TWO 4-bit scales per byte
//
// SCALE GRANULARITY IS 16 WEIGHTS, NOT 32. The 8 scale bytes hold SIXTEEN
// nibbles, and ggml's own dequant broadcasts db over (16, 2, 8): group g covers
// qs[2g] and qs[2g+1], i.e. 16 values. Treating the scales as eight per-32
// nibbles would read only half the scale bytes and fail *plausibly* -- right
// shape, wrong values, which a cosine check can hide.
//     db    = d * (0.5f + s) * 0.25f     // s = nibble of that 16-weight group
//     entry = qs[e]; grid = entry & 511; signs = ksigns_iq2xs[entry >> 9]
//     value v of entry e flips when (signs >> v) & 1
//
// Each entry expands to EIGHT values (two int32 dp4a words) where IQ3_XXS's
// expand to four, so one 32-weight slice is 4 entries carrying 2 scales. Grid
// magnitudes are {8, 25, 43}, so sign-flipped bytes stay in int8 range and feed
// __dp4a directly. Oracle: fni8.quant.iq2xs (fni8#317).
// Adapted (MIT->BSD-3) from llama.cpp vec_dot_iq2_xs_q8_1 + dequantize_row_iq2_xs.
// ===========================================================================
