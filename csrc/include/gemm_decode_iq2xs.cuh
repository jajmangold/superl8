template <typename OutT, int MAX_M>
__global__ void __launch_bounds__(DEC_THREADS)
gemm_decode_iq2xs_kernel(const int8_t* __restrict__ x, const float* __restrict__ x_scale,
                         const uint8_t* __restrict__ w, OutT* __restrict__ out,
                         int M, int N, int K, int num_sb) {
  const int warp_id = threadIdx.x / DEC_WARP;
  const int lane = threadIdx.x % DEC_WARP;
  const int n = blockIdx.x * DEC_WARPS_PER_BLOCK + warp_id;
  if (n >= N) return;
  const int nsub = K / 32;
  const int64_t row_bytes = (int64_t)num_sb * IQ2XS_TYPE_SIZE;
  const uint8_t* wrow = w + (int64_t)n * row_bytes;

  float f_acc[MAX_M];
#pragma unroll
  for (int m = 0; m < MAX_M; ++m) f_acc[m] = 0.f;

  for (int i = lane; i < nsub; i += DEC_WARP) {
    const int sb = i >> 3, j32 = i & 7;
    const uint8_t* blk = wrow + (int64_t)sb * IQ2XS_TYPE_SIZE;
    // 74 is even and qs starts at +2, so these uint16 reads are 2-byte aligned --
    // the same assumption dec_ld_u32 already makes.
    const uint16_t* qs = reinterpret_cast<const uint16_t*>(blk + 2) + 4 * j32;
    const float d = __half2float(*reinterpret_cast<const __half*>(blk));
    // Both 16-weight groups of this 32-weight slice share ONE scale byte:
    // group 2*j32 is its low nibble, group 2*j32+1 its high nibble.
    const int sbyte = blk[66 + j32];
    const float dbA = d * (0.5f + (float)(sbyte & 0x0F)) * 0.25f;
    const float dbB = d * (0.5f + (float)((sbyte >> 4) & 0x0F)) * 0.25f;

    int32_t q[8];
#pragma unroll
    for (int p = 0; p < 4; ++p) {
      const uint32_t e = qs[p];
      const uint2 gv = __ldg(reinterpret_cast<const uint2*>(&kIq2xsGrid[e & 511][0]));
      const uint32_t g[2] = {gv.x, gv.y};
      const int sgn = __ldg(&kSignsIq2xs[e >> 9]);
#pragma unroll
      for (int h = 0; h < 2; ++h) {
        const int mb = sgn >> (4 * h);          // 4 sign bits for this dp4a word
        const uint32_t sbits = (uint32_t)(mb & 1) | ((uint32_t)((mb >> 1) & 1) << 8) |
                               ((uint32_t)((mb >> 2) & 1) << 16) |
                               ((uint32_t)((mb >> 3) & 1) << 24);
        const int neg = __vcmpne4(sbits, 0x00000000u);
        q[2 * p + h] = __vsub4((int)(g[h] ^ (uint32_t)neg), neg);
      }
    }
#pragma unroll
    for (int m = 0; m < MAX_M; ++m) {
      if (m >= M) break;
      const int4* xr = reinterpret_cast<const int4*>(x + (int64_t)m * K);
      const int4 xv0 = xr[i * 2], xv1 = xr[i * 2 + 1];
      int32_t sA = 0, sB = 0;                   // entries 0,1 -> group A; 2,3 -> B
      sA = __dp4a(xv0.x, q[0], sA);
      sA = __dp4a(xv0.y, q[1], sA);
      sA = __dp4a(xv0.z, q[2], sA);
      sA = __dp4a(xv0.w, q[3], sA);
      sB = __dp4a(xv1.x, q[4], sB);
      sB = __dp4a(xv1.y, q[5], sB);
      sB = __dp4a(xv1.z, q[6], sB);
      sB = __dp4a(xv1.w, q[7], sB);
      f_acc[m] += dbA * (float)sA + dbB * (float)sB;
    }
  }
#pragma unroll
  for (int m = 0; m < MAX_M; ++m) {
    if (m >= M) break;
    float v = f_acc[m];
#pragma unroll
    for (int off = 16; off > 0; off >>= 1) v += __shfl_xor_sync(0xFFFFFFFFu, v, off);
    if (lane == 0) out[(int64_t)m * N + n] = float_to<OutT>(v * x_scale[m]);
  }
}

