template <typename OutT, int MAX_M>
__global__ void __launch_bounds__(DEC_THREADS)
gemm_decode_iq1s_kernel(const int8_t* __restrict__ x, const float* __restrict__ x_scale,
                        const uint8_t* __restrict__ w, OutT* __restrict__ out,
                        int M, int N, int K, int num_sb) {
  const int warp_id = threadIdx.x / DEC_WARP;
  const int lane = threadIdx.x % DEC_WARP;
  const int n = blockIdx.x * DEC_WARPS_PER_BLOCK + warp_id;
  if (n >= N) return;
  const int nsub = K / 32;
  const int64_t row_bytes = (int64_t)num_sb * IQ1S_TYPE_SIZE;
  const uint8_t* wrow = w + (int64_t)n * row_bytes;

  float f_acc[MAX_M];
#pragma unroll
  for (int m = 0; m < MAX_M; ++m) f_acc[m] = 0.f;

  for (int i = lane; i < nsub; i += DEC_WARP) {
    const int sb = i >> 3, ib32 = i & 7;
    const uint8_t* blk = wrow + (int64_t)sb * IQ1S_TYPE_SIZE;
    const uint8_t* qs = blk + 2 + 4 * ib32;
    // qh sits at byte 34, so it is only 2-byte aligned; assemble it from bytes.
    const uint8_t* qhp = blk + 34 + 2 * ib32;
    const uint32_t qh = (uint32_t)qhp[0] | ((uint32_t)qhp[1] << 8);

    // 8*(g + delta) == 8g +- 1, so fold the 1/8 into the scale.
    const float dl = __half2float(*reinterpret_cast<const __half*>(blk)) *
                     (float)(2 * ((qh >> 12) & 7) + 1) * 0.125f;
    // +delta -> +1 in every byte lane; -delta -> -1 (0xFF per byte).
    const uint32_t dword = (qh & 0x8000u) ? 0xFFFFFFFFu : 0x01010101u;

    int32_t q[8];
#pragma unroll
    for (int e = 0; e < 4; ++e) {
      const uint32_t idx = (uint32_t)qs[e] | (((qh >> (3 * e)) & 7u) << 8);
      // 8-byte row, 8-byte aligned: one __ldg of a uint2 beats two scalar loads.
      const uint2 gw = __ldg(reinterpret_cast<const uint2*>(&kIq1sGrid[idx][0]));
      q[2 * e]     = (int32_t)__vadd4(gw.x, dword);
      q[2 * e + 1] = (int32_t)__vadd4(gw.y, dword);
    }
#pragma unroll
    for (int m = 0; m < MAX_M; ++m) {
      if (m >= M) break;
      const int4* xr = reinterpret_cast<const int4*>(x + (int64_t)m * K);
      const int4 xv0 = xr[i * 2], xv1 = xr[i * 2 + 1];
      int32_t si = 0;
      si = __dp4a(xv0.x, q[0], si);
      si = __dp4a(xv0.y, q[1], si);
      si = __dp4a(xv0.z, q[2], si);
      si = __dp4a(xv0.w, q[3], si);
      si = __dp4a(xv1.x, q[4], si);
      si = __dp4a(xv1.y, q[5], si);
      si = __dp4a(xv1.z, q[6], si);
      si = __dp4a(xv1.w, q[7], si);
      f_acc[m] += dl * (float)si;
    }
  }
#pragma unroll
  for (int m = 0; m < MAX_M; ++m) {
    if (m >= M) break;
    float v = f_acc[m];
#pragma unroll
    for (int off = 16; off > 0; off >>= 1) v += __shfl_xor_sync(0xFFFFFFFFu, v, off);
    if (lane == 0) out[(int64_t)m * N + n] = float_to<OutT>(v * x_scale[m]);
  }
}

