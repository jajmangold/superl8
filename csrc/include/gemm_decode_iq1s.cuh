// IQ1_S decode - warp-per-column MMVQ over ggml's 2048-entry TERNARY grid.
// Block (50 B / 256 weights, 1.5625 bpw):
//     +0   d        fp16 super-block scale
//     +2   qs[32]   low 8 bits of the grid index, 4 per 32-weight sub-block
//     +34  qh[8]    uint16 per sub-block: 3 index bits x4, a scale, a delta sign
// Per sub-block ib32 with qh = qh[ib32]:
//     idx(e) = qs[4*ib32 + e] | (((qh >> 3*e) & 7) << 8)   // 11 bits, e = 0..3
//     dl     = d * (2 * ((qh >> 12) & 7) + 1)
//     delta  = (qh & 0x8000) ? -0.125f : +0.125f
//     value  = dl * (grid_value + delta)                   // NO sign bits
//
// IQ1_S is the one i-quant that cannot feed its codes to __dp4a directly: the
// +delta makes the effective weight non-integer. But grid_value is ternary and
//     8 * (grid_value + delta) == 8*grid_value +- 1  in  {-9,-7,-1,+1,+7,+9}
// exactly -- all integral and far inside int8. So the table below stores
// 8*grid_value (hence the -8 / 0 / +8 entries), the delta becomes a per-byte
// +-1 via a single __vadd4, and the factor folds into the scale as dl*0.125f.
// No multiply and no unpacking in the inner loop.
//
// Grid table: 2048 entries x 8 int8 codes = 16 KiB of __constant__, stored
// plainly. Measured usage of the tables already on master is 3216 B, so even
// with all four new i-quant kernels this stays near 33 KiB of the 64 KiB sm_70
// budget. The rows are 16-byte aligned so each 8-code entry can be consumed as
// two aligned 32-bit words.
// Oracle: fni8.quant.iq1s (fni8#317). Adapted (MIT->BSD-3) from llama.cpp's
// vec_dot_iq1_s_q8_1 + dequantize_row_iq1_s.
// ===========================================================================
