// IQ2_S decode -- warp-per-column MMVQ over ggml's 1024-entry codebook grid.
// Block (82 B / 256 weights, 2.5625 bpw):
//     +0   d         fp16 super-block scale
//     +2   qs[32]    low 8 bits of the grid index (one byte per 8 weights)
//     +34  signs[32] one byte per grid entry: 8 EXPLICIT sign bits (set = negative)
//     +66  qh[8]     one byte per 32-weight sub-block; 2 bits per entry (index bits 8-9)
//     +74  scales[8] two 4-bit fields per byte -> SIXTEEN scales, one per 16 weights
//
// Two things differ from IQ3_S and both fail *plausibly* if copied across:
//   * a grid entry here is EIGHT magnitudes, not four, so a 32-weight sub-block is
//     4 entries (8 dp4a words), not 8;
//   * the scale granularity is 16 weights, so each 32-weight sub-block carries TWO
//     scales -- the low nibble of scales[ib32] for weights 0-15, the high nibble for
//     16-31. Applying one scale per 32 weights still produces well-shaped output.
//
// For entry i in 0..3 of sub-block ib32 (e = 4*ib32 + i):
//     idx  = qs[e] | (((qh[ib32] >> (2*i)) & 3) << 8)     // 10-bit -> 1024 entries
//     sign = signs[e] bit j flips magnitude j
//     db   = d * (0.5f + scale_nibble) * 0.25f
// Grid magnitudes are {8, 25, 43}, so sign-flipped bytes stay in int8 range and feed
// __dp4a directly. Oracle: fni8.quant.iq2s (fni8#317), bit-exact vs gguf-py.
// Adapted (MIT->BSD-3) from llama.cpp vec_dot_iq2_s_q8_1 + dequantize_row_iq2_s.
// ===========================================================================
