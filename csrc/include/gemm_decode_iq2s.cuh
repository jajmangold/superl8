template <typename OutT, int MAX_M>
__global__ void __launch_bounds__(DEC_THREADS)
gemm_decode_iq2s_kernel(const int8_t* __restrict__ x, const float* __restrict__ x_scale,
                        const uint8_t* __restrict__ w, OutT* __restrict__ out,
                        int M, int N, int K, int num_sb) {
  const int warp_id = threadIdx.x / DEC_WARP;
  const int lane = threadIdx.x % DEC_WARP;
  const int n = blockIdx.x * DEC_WARPS_PER_BLOCK + warp_id;
  if (n >= N) return;
  const int nsub = K / 32;                       // 32-weight sub-blocks along K
  const int64_t row_bytes = (int64_t)num_sb * IQ2S_TYPE_SIZE;
  const uint8_t* wrow = w + (int64_t)n * row_bytes;

  float f_acc[MAX_M];
#pragma unroll
  for (int m = 0; m < MAX_M; ++m) f_acc[m] = 0.f;

  for (int i = lane; i < nsub; i += DEC_WARP) {
    const int sb = i >> 3, ib32 = i & 7;         // super-block, sub-block within it
    const uint8_t* blk = wrow + (int64_t)sb * IQ2S_TYPE_SIZE;
    const uint8_t* qs = blk + 2 + 4 * ib32;      // 4 grid entries per sub-block
    const uint8_t* sg = blk + 34 + 4 * ib32;     // one sign byte per entry
    const int qh = blk[66 + ib32];
    const int scb = blk[74 + ib32];              // TWO scales live in this byte
    const float d = __half2float(*reinterpret_cast<const __half*>(blk));
    const float dsc_lo = d * (0.5f + (float)(scb & 0xF)) * 0.25f;         // weights 0-15
    const float dsc_hi = d * (0.5f + (float)((scb >> 4) & 0xF)) * 0.25f;  // weights 16-31

    // LG THROTTLE (fni8#334): fold the per-element qs/sg byte gathers into two 32-bit
    // loads, as IQ3_S now does (+19.8% there) and as Q4_K/Q6_K already did.
    // Alignment: qs = blk+2+4*ib32 and sg = blk+34+4*ib32 are both even.
    const uint32_t qs_w = dec_ld_u32(qs);   // qs[0..3]
    const uint32_t sg_w = dec_ld_u32(sg);   // sg[0..3]

    int32_t q[8];
#pragma unroll
    for (int p = 0; p < 4; ++p) {
      const int idx = (int)((qs_w >> (8 * p)) & 0xFFu) | (((qh >> (2 * p)) & 3) << 8);
      const uint2 g = __ldg(reinterpret_cast<const uint2*>(&kIq2sGrid[idx][0]));
      const uint32_t g0 = g.x, g1 = g.y;
      const int sgn = (int)((sg_w >> (8 * p)) & 0xFFu);
      const int mb0 = sgn & 0xF, mb1 = (sgn >> 4) & 0xF;
      const uint32_t s0 = (uint32_t)(mb0 & 1) | ((uint32_t)((mb0 >> 1) & 1) << 8) |
                          ((uint32_t)((mb0 >> 2) & 1) << 16) | ((uint32_t)((mb0 >> 3) & 1) << 24);
      const uint32_t s1 = (uint32_t)(mb1 & 1) | ((uint32_t)((mb1 >> 1) & 1) << 8) |
                          ((uint32_t)((mb1 >> 2) & 1) << 16) | ((uint32_t)((mb1 >> 3) & 1) << 24);
      const int neg0 = __vcmpne4(s0, 0x00000000u);   // 0xFF per byte to negate
      const int neg1 = __vcmpne4(s1, 0x00000000u);
      q[2 * p]     = __vsub4((int)(g0 ^ (uint32_t)neg0), neg0);   // (b^0xFF) - (-1) = -b
      q[2 * p + 1] = __vsub4((int)(g1 ^ (uint32_t)neg1), neg1);
    }
#pragma unroll
    for (int m = 0; m < MAX_M; ++m) {
      if (m >= M) break;
      const int4* xr = reinterpret_cast<const int4*>(x + (int64_t)m * K);
      const int4 xv0 = xr[i * 2], xv1 = xr[i * 2 + 1];   // 32 int8 = 8 dp4a words
      int32_t lo = 0, hi = 0;
      lo = __dp4a(xv0.x, q[0], lo);       // entries 0-1 -> weights 0-15, dsc_lo
      lo = __dp4a(xv0.y, q[1], lo);
      lo = __dp4a(xv0.z, q[2], lo);
      lo = __dp4a(xv0.w, q[3], lo);
      hi = __dp4a(xv1.x, q[4], hi);       // entries 2-3 -> weights 16-31, dsc_hi
      hi = __dp4a(xv1.y, q[5], hi);
      hi = __dp4a(xv1.z, q[6], hi);
      hi = __dp4a(xv1.w, q[7], hi);
      f_acc[m] += dsc_lo * (float)lo + dsc_hi * (float)hi;
    }
  }
#pragma unroll
  for (int m = 0; m < MAX_M; ++m) {
    if (m >= M) break;
    float v = f_acc[m];
#pragma unroll
    for (int off = 16; off > 0; off >>= 1) v += __shfl_xor_sync(0xFFFFFFFFu, v, off);
    if (lane == 0) out[(int64_t)m * N + n] = float_to<OutT>(v * x_scale[m]);
  }
}

